"""The gauntlet (Nov 21, Joseph): a pseudo-run. One party fights Fodder, then Regulars, then an Elite, then a Boss, with
nothing restored in between: HP, MP, the pouch, Wounded and the dead carry (dive_spec: what carries between rooms). Per
fight wins from full HP flatter a party; this asks how far it gets.

    python3 gauntlet.py [runs]          # markdown: per party and leg, how far runs get and what they bring to each room

Rooms are the sweep's shapes (composer.shaped_room), in a place picked per room: Fodder is a fodder room of 3; Regulars a
fodder room of 3 and two Regular adds; Elite an elite room of 4; Boss a boss room of 4. Rooms are mirrored (composer.mirror: reach slots, Nov 23). A win stabilises the Dying at
1 HP, Wounded (the engine's own rule); a hero who dies stays dead; the run ends at the first loss. Between rooms a hero's
fight-only state is cleared (statuses, stages, wind-ups, knots); HP and MP aren't. The AI plays: a floor.
Each party carries Joseph's usual pouch: a Strong Life Draught, an Iron Throwing Hammer and a Thunderpot."""
import random, statistics, sys
from engine import *
from composer import CALIB_PLACES, shaped_room, catalog, spawn

CAT = catalog()
from collections import Counter
BRAIN = Counter()          # the brains' picks and fallbacks over every room (step 3: "every fallback is counted")
STAGES = [("Fodder", "fodder", 3, None), ("Regulars", "fodder", 3, "Regular"), ("Elite", "elite", 4, None), ("Boss", "boss", 4, None)]
CAMP_BEFORE = "Boss"       # D9 (Nov 24): the column before every boss is a camp (dive_spec); everyone rests (no carving here)
POUCH = [[["strong_life", 1]], [["iron_hammer", 1]], [["thunderpot", 1]]]
PARTIES = [("Dagskald", "Skurmar", "Vasara"), ("Vasara", "Ullar", "Brennumar")]

def run(classes, leg, seed):
    rng = random.Random(seed)
    party = [build_hero(c, leg, SHEET_LEVEL) for c in classes]
    for h, p in zip(party, POUCH): h.pouch = [list(i) for i in p]
    out = []
    for name, kind, budget, add in STAGES:
        alive = [h for h in party if h.state != "dead"]
        if not alive: break
        if name == CAMP_BEFORE:                                         # the camp: what the party brings is after it
            for h in alive: rest(h)
        hp = sum(h.hp for h in alive) / sum(h.maxhp for h in party)       # the share of the party's full HP it brings
        mp_pool = sum(h.maxmp for h in party)
        mp = sum(h.mp for h in alive) / mp_pool if mp_pool else 0.0
        for h in alive: settle(h)
        picks = shaped_room(rng, CAT, rng.choice(CALIB_PLACES), kind, budget, add, mirrored=True)
        b = Battle(alive, spawn(picks, ENEMY_LEVEL), random.Random(rng.getrandbits(32)), profile="new")
        w = b.fight()
        BRAIN.update(b.brain_stats)
        falls = sum(h.stats["downs"] for h in alive)
        items = sum(n for h in party for _, n in h.pouch)
        out.append(dict(stage=name, hp=hp, mp=mp, won=w == "party", falls=falls, rounds=b.round, items=items,
                        dead=sum(h.state == "dead" for h in party)))
        if w != "party": break
    return out

def report(n=100):
    L = ["# The gauntlet (generated by sim/gauntlet.py)", "",
         f"{n} runs per party and leg. Fodder 3, then Fodder 3 + 2 Regulars, then Elite 4, then a camp (everyone Rests: "
         "2/3 of HP and MP, Wounded heals; D9), then Boss 4; otherwise nothing restored (HP, MP, the pouch, Wounded and the dead carry); rooms are mirrored (reach slots, Nov 23). The AI plays: a floor. *Brings* is the HP (and MP) the "
         "party walks in with, as a share of its full pools; *falls* counts heroes downed in that room (a won room stands "
         "them up at 1 HP, Wounded).", ""]
    for classes in PARTIES:
        for leg in (1, 2, 3):
            runs = [run(classes, leg, 10_000 * leg + i) for i in range(n)]
            L += [f"**{' / '.join(classes)}, kit leg {leg}:**", "",
                  "| Room | Reached | Won | Brings HP | Brings MP | Rounds (wins) | Falls | Items left after |", "|---|---|---|---|---|---|---|---|"]
            for i, (name, *_ ) in enumerate(STAGES):
                at = [r[i] for r in runs if len(r) > i]
                if not at: L.append(f"| {name} | 0% | 0% | - | - | - | - | - |"); continue
                won = [s for s in at if s["won"]]
                L.append(f"| {name} | {len(at) / n:.0%} | {len(won) / n:.0%} | {statistics.mean(s['hp'] for s in at):.0%} | "
                         f"{statistics.mean(s['mp'] for s in at):.0%} | {statistics.mean(s['rounds'] for s in won) if won else 0:.1f} | "
                         f"{statistics.mean(s['falls'] for s in at):.2f} | {statistics.mean(s['items'] for s in at):.1f} |")
            L.append("")
    L += ["## The brains (step 3)", "", "How often each pack plan was taken (picked or switched to), and each Bein job's picks by "
          "rule; a fallback is a turn no rule fitted, so the shared scorer chose (weighing the plan's focus).", "",
          "| Who | Rule | Times | Share |", "|---|---|---|---|"]
    for who in sorted({k[0] for k in BRAIN}):
        rows = {k[1]: v for k, v in BRAIN.items() if k[0] == who}; tot = sum(rows.values())
        for rule, v in sorted(rows.items(), key=lambda x: -x[1]):
            L.append(f"| {who} | {rule} | {v} | {v / tot:.0%} |")
    return "\n".join(L)

if __name__ == "__main__":
    print(report(int(sys.argv[1]) if len(sys.argv) > 1 else 100))
